"""Render eval/results/REPORT.md from the result files, so every number in it comes from a file in this folder.

  python eval/report.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p, encoding="utf8")) if os.path.exists(p) else None


def pct(w):
    if not w:
        return "N/A"
    return f"{w['p'] * 100:.0f}% ({w['k']}/{w['n']}; 95% CI {w['lo'] * 100:.0f}–{w['hi'] * 100:.0f}%)"


def main():
    cal, test, perf, inter = load("calibration.json"), load("test_metrics.json"), load("perf.json"), load("interference.json")
    agr = json.load(open(os.path.join(HERE, "labels", "agreement.json"), encoding="utf8")) if os.path.exists(os.path.join(HERE, "labels", "agreement.json")) else None
    L = ["# SceneGap Edge: evaluation report", "",
         "Generated by `eval/report.py` from the JSON files in `eval/results/` and `eval/labels/`. Protocol: `eval/PROTOCOL.md`.",
         "All model numbers come from the CPU/GPU **reference** backend (OpenAI CLIP ViT-B/32, fp32). No UGen300 result exists yet (`not_run`).",
         "Scope: 11 café shots; 44 Wikimedia Commons clips transcoded to H.264 (at most 1280 px wide); the held-out test split is 26 clips, 14 min.", ""]
    if agr:
        L += ["## Labels", "",
              f"- Two independent AI annotator sessions on the same 1 fps contact sheets, then an AI third pass on every disagreement ({agr['third_pass_decisions']} frame × requirement labels).",
              f"- Clip × requirement pairs agreeing (interval IoU ≥ 0.5 or both empty): {agr['pairs_agreeing_iou_ge_0.5_or_both_empty']}/{agr['clip_requirement_pairs']} "
              f"({agr['pair_agreement'] * 100:.1f}%). Sample-level Cohen's κ = {agr['sample_level']['cohen_kappa']}.",
              f"- Consistency pass (added after labelling, before calibration): the third-pass rules were re-applied to the {agr['consistency_pass']['checked']} agreed positives of SH-03, SH-04, SH-09 and SH-11 "
              f"(of {agr['sample_level']['ab']} agreed positives overall); {agr['consistency_pass']['removed']} were removed (primary gold). The pass could only remove labels; the lenient gold keeps them.",
              "- Split note: one author pair (Duchardt & Engel) has a clip in dev (022) and one in test (025), because their author strings differ by one space. "
              "Found after scoring; dev used 022 only for the global τ.", ""]
    if cal:
        L += ["## Calibration (dev only)", "",
              f"- Crop policy frozen: `{cal['crop']}`; τ = {cal['chosen']['tau']} (dev sample-level F1 {cal['chosen']['f1']}, "
              f"{cal['pairs']} sample×requirement pairs, {cal['positives']} positive).",
              "- Alternatives: " + "; ".join(f"{a['crop']}: τ {a['chosen']['tau']}, F1 {a['chosen']['f1']}" for a in cal["alternatives"]),
              f"- Frozen at {cal['frozen_at']}, model fingerprint `{cal['fingerprint']}`.", ""]
    if test:
        L += ["## Test split, scored once", "", f"Scored at {test['scored_at']} on {len(test['test_clips'])} clips with τ = {test['tau']} ({test['crop']}).", "",
              "### Retrieval (top 5 per requirement)", "",
              "Recall@5 = share of requirements whose top 5 contains a correct segment (≥ 0.5 s overlap with gold); Precision@5 = share of the top-5 items that are correct. "
              "Keyword candidates are whole clips.", "", "| Method | Recall@5 | Precision@5 |", "|---|---|---|"]
        names = {"keyword": "Title keyword match", "single_frame": "Single-frame semantic", "full": "SceneGap (semantic + duration + densify)"}
        for m in ("keyword", "single_frame", "full"):
            L.append(f"| {names[m]} | {pct(test['retrieval'][m]['recall_at_5'])} | {pct(test['retrieval'][m]['precision_at_5'])} |")
        L += ["", "The duration and densify rules did not improve retrieval on this test: single-frame search hits 8 of 11, the full system 7 of 11 "
                  "(one requirement; the intervals overlap). What the rules add, rejecting runs that are too short, is not measured by Recall@5."]
        rl = test.get("review_load")
        if rl:
            L += ["", f"Review-load proxy: {rl['candidate_seconds_to_review']} s of candidates to play for {rl['requirements']} requirements, "
                      f"versus {rl['library_seconds']} s to watch the test library once. {rl['note']}."]
        L += ["", f"### Project simulation ({len(test['projects'])} projects × {test['project_size']} test clips)", "",
              "Unit: one shot in one project. 'Missing' = gold has no qualifying segment in that project's clips. Gap recall = missing shots answered "
              "`not_found`; wrong reshoot = present shots answered `not_found`; unknown = `partial` or `unverifiable` over all pairs; "
              "candidate where gold has none = missing shots answered `candidate`. Counts are shown as k/n.", "",
              "| Method | Gap recall | Wrong reshoot rate | Unknown rate | Candidate where gold has none |", "|---|---|---|---|---|"]
        for m in ("keyword", "single_frame", "full"):
            s = test["simulation"][m]
            L.append(f"| {names[m]} | {pct(s['gap_recall'])} | {pct(s['wrong_reshoot_rate'])} | {pct(s['unknown_rate'])} | {pct(s['false_candidate_rate'])} |")
        sens = test.get("sensitivity_lenient_gold")
        if sens:
            L += ["", "### Sensitivity: lenient gold (agreed + third pass, no consistency pass)", "", "| Method | Recall@5 | Precision@5 | Gap recall | Wrong reshoot |", "|---|---|---|---|---|"]
            for m in ("keyword", "single_frame", "full"):
                L.append(f"| {names[m]} | {pct(sens['retrieval'][m]['recall_at_5'])} | {pct(sens['retrieval'][m]['precision_at_5'])} | "
                         f"{pct(sens['simulation'][m]['gap_recall'])} | {pct(sens['simulation'][m]['wrong_reshoot_rate'])} |")
        L += ["", "False-ready rate: N/A. The system never marks a requirement done; a person confirms.", "",
              "### Per requirement (full system, whole test library)", "", "| Req | Query | Clips with gold | Status | Correct / returned |", "|---|---|---|---|---|"]
        for r in test["per_requirement"]:
            L.append(f"| {r['requirement_id']} | {r['query_en']} | {r['gold_clips']} | {r['status']} | {r['full']['correct']}/{r['full']['returned']} |")
        L.append("")
    rc = load("rule_check.json")
    if rc:
        L += ["## Rule check on controlled cases (separate experiment)", "",
              f"`eval/rule_check.py`: {rc['cases']} short cases cut from real Commons footage so the right answer is known "
              f"(a 4 s pour must pass a 3 s rule, a 2 s pour must not, ...). Frozen calibration, one project per case. "
              f"**{rc['correct']} of {rc['cases']} judged right.**", "",
              "| Case | Shot | Should | SceneGap | Reasons | Right |", "|---|---|---|---|---|---|"]
        for r in rc["rows"]:
            L.append(f"| {r['tests']} | {r['shot']} | {r['expected']} | {'pass' if r['passed'] else 'not pass'} ({r['status']}) | {', '.join(r['reasons'] or []) or '—'} | {'yes' if r['correct'] else '**no**'} |")
        L += ["", "The two misses are limits of the method, not bugs: CLIP scores a finished latte as close to 'coffee being poured', "
                  "and takes are told apart by file hash, so a re-encoded copy counts as a second take.", ""]
    dg = load("drop_diagnosis_019.json")
    if dg:
        r4 = dg["SH-04"]["runs"][0]
        L += ["## Why the full system lost one top-5 hit (diagnosis, no rescoring)", "",
              "Single-frame search hit SH-03 and SH-04, the full system did not (it gained SH-06). The correct clip for both is 019 (grinding "
              f"beans in a blender). Run on its own, 019 passes every rule: SH-04 {r4['start_s']:.0f}–{r4['end_s']:.0f} s, "
              f"run {r4['len_s']:.0f} s, all conditions pass. So the rules did not reject it: in the test library the full system ranks runs "
              "by their average similarity, while single-frame search uses the peak frame, and other runs averaged higher. Stage II ranks runs by peak.", ""]
    ex = load("explore_dev_gap_tradeoff.json")
    if ex:
        L += ["## After the test: why gap recall is 0 (dev split only, exploratory)", "",
              "The frozen τ was chosen by frame-level F1 and is too low for project-level gap detection: almost every requirement",
              "finds some candidate. Sweeping τ on dev mini-projects shows the trade-off a project-level objective must handle:", "",
              "| Score | τ / margin | Gap recall | Wrong reshoot |", "|---|---|---|---|"]
        for key, label in (("rows", "raw cosine"), ("margin_rows", "margin over negative prompts")):
            for r in ex.get(key, []):
                L.append(f"| {label} | {r['tau']} | {r['gap_recall']['p'] * 100:.0f}% | {r['wrong_reshoot']['p'] * 100:.0f}% |")
        L += ["", "Not used to rescore test. Stage II pre-registers a project-level objective (per-query thresholds, margin score) and",
              "scores it once on new footage.", ""]
    if perf:
        L += ["## Performance (desktop reference)", "", f"Measured {perf['measured_at']}. {perf['note']}.", "",
              "| Backend | Device | Search p50 / p95 over 10,000 segments | Mean analyse time per clip-second |", "|---|---|---|---|"]
        for name, b in perf["backends"].items():
            secs = sum(c["duration_s"] for c in b["per_clip"])
            tot = sum(c["analyse_total_s"] for c in b["per_clip"])
            L.append(f"| {name} | {b['device']} | {b['search_ms']['p50']} / {b['search_ms']['p95']} ms | {tot / secs * 1000:.0f} ms per second of video ({secs:.0f} s of video) |")
        L += ["", "Timed: decode and embedding of six short transcoded clips (85 s), warm model; import and hashing not included.", ""]
    if inter:
        L += ["## Playback interference (proxy for PRD 24.3)", "", f"{inter['playback']}; load: {inter['load']}. {inter['note']}", "",
              "| Analysis running | Late frames | Frame work p95 (budget 33.3 ms) | Clips analysed during playback |", "|---|---|---|---|"]
        for k, v in inter["summary"].items():
            L.append(f"| {k} | {v['late_share_mean'] * 100:.1f}% | {v['frame_work_ms_p95_max']} ms | {v['load_clips_finished']} |")
        L += ["| UGen300 | not_run | not_run | not_run |", "",
              "The playback clip is a synthetic 1080p30 test pattern (`testsrc2`). Clips analysed = repeated runs over the same 8 clips.", ""]
    L += ["## Not measured yet", "", "- Any UGen300 / Hailo-10H number (G1 gate needs the device).", "- Power (no meter used).",
          "- User study (PRD 22): no participants yet; time-saving is a hypothesis.", "- NLE timeline interference (the proxy above is not an NLE).",
          "- Human labels: all labels so far come from AI annotator sessions.",
          "", "Intervals are Wilson 95% intervals that treat each item as independent; projects share clips and gaps cluster by requirement, so the real uncertainty is larger."]
    open(os.path.join(RES, "REPORT.md"), "w", encoding="utf8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
